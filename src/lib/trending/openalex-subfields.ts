export const OPENALEX_SUBFIELDS = SUBFIELDS.map(([id, label, fieldId]) => ({
  id: `https://openalex.org/subfields/${id}`,
  label,
  fieldId: `https://openalex.org/fields/${fieldId}`,
}))

export function openAlexSubfield(id: string) {
  const match = /^(?:https?:\/\/openalex\.org\/)?(?:subfields\/)?(\d{4})\/?$/.exec(id)
  return match ? OPENALEX_SUBFIELDS.find((subfield) => subfield.id === `https://openalex.org/subfields/${match[1]}`) : undefined
}

export function subfieldsForField(id: string) {
  const field = openAlexField(id)
  return field ? OPENALEX_SUBFIELDS.filter((subfield) => subfield.fieldId === field.id) : []
}

